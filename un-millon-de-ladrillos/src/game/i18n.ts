export type Lang = 'es' | 'en';
export const dict = { es, en };
export let lang: Lang = (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
export function setLang(l: Lang) { lang = l; }
export function t() { return dict[lang]; }
const loc = () => (lang === 'es' ? 'es-AR' : 'en-US');
export function fmt(n: number, d = 0) {
  if (Math.abs(n) >= 1e6) return new Intl.NumberFormat(loc(), { maximumFractionDigits: 2 }).format(n / 1e6) + ' M';
  return new Intl.NumberFormat(loc(), { maximumFractionDigits: d, minimumFractionDigits: d }).format(n);
}
export function fmtInt(n: number) { return new Intl.NumberFormat(loc(), { maximumFractionDigits: 0 }).format(Math.round(n)); }
export function fmtTime(s: number) {
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), ss = Math.floor(s % 60);
  return h > 0 ? `${h}h ${m}m` : `${m}m ${String(ss).padStart(2, '0')}s`;
}
